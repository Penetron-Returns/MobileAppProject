#!/usr/bin/env node
/**
 * Bundles React, react-dom and `bot-avatars` into one self-contained script so
 * the app can draw the animated Clovie offline inside a WebView.
 *
 *   node scripts/build-clovie-embed.mjs
 *
 * Writes `src/features/brand/clovieBundle.generated.ts` (the script as a
 * string). Re-run it after upgrading `bot-avatars`; the output is committed so
 * Metro never needs esbuild.
 */
import { build } from 'esbuild';
import { execFileSync } from 'node:child_process';
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(
  here,
  '../src/features/brand/clovieBundle.generated.ts',
);

const result = await build({
  entryPoints: [path.join(here, 'clovie-embed-entry.mjs')],
  bundle: true,
  write: false,
  minify: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2020',
  charset: 'ascii',
  define: { 'process.env.NODE_ENV': '"production"' },
  nodePaths: [path.resolve(here, '../../../node_modules')],
});

// A literal closing script tag would end the inline <script> early.
const js = result.outputFiles[0].text.replace(/<\/script/gi, '<\/script');
const source = `// Generated by scripts/build-clovie-embed.mjs. Do not edit.
export const CLOVIE_BUNDLE =
  ${JSON.stringify(js)};
`;
await writeFile(out, source);
// Match the repo's Prettier style so lint stays clean.
execFileSync('npx', ['prettier', '--write', out], {
  shell: true,
  stdio: 'ignore',
});
console.log(
  `wrote ${path.relative(process.cwd(), out)} (${(js.length / 1024).toFixed(0)} KB)`,
);
